"""
Project Alpha: Autonomous Companion Behavior & Emotion Engine.
Wires real-time camera perception into Alpha's emotional states, GC9A01 eye animations,
pan/tilt neck servos, Wall-E procedural sound effects, episodic memory, and Gemini neural cortex.
"""

import time
import threading
from enum import Enum
from dataclasses import dataclass
from typing import Optional, Dict, Any, Tuple

from core.eye_animator import Emotion
from core.vision_pipeline import FaceTrackingResult


class BehaviorState(Enum):
    IDLE = "idle"
    GREETING = "greeting"
    TRACKING = "tracking"
    BONDING = "bonding"
    SMILING = "smiling"
    STARTLED = "startled"
    SEARCHING = "searching"
    DISAPPOINTED = "disappointed"


@dataclass
class BehaviorAction:
    """Action plan generated by the behavior engine for physical & expressive execution."""
    state: BehaviorState
    emotion: Emotion
    gaze_x: float
    gaze_y: float
    target_pan: float
    target_tilt: float
    sound: Optional[str] = None
    gesture: Optional[str] = None
    speech_message: Optional[str] = None
    observation_log: Optional[str] = None
    inner_thought: Optional[str] = None
    observed_visual: Optional[str] = None
    trigger_blink: bool = False
    trigger_wink: bool = False
    num_faces: int = 1
    identified_name: Optional[str] = None


class AlphaBehaviorEngine:
    """
    Coordinates emotional transitions, lifelike gaze following,
    and responsive Wall-E companion interactions driven by camera feed and Gemini neural cortex.
    """

    def __init__(self, brain: Optional[Any] = None):
        self.brain = brain
        self.current_state = BehaviorState.IDLE
        self.tracking_start_time = 0.0
        self.last_seen_time = 0.0
        self.last_lost_time = time.time()
        self.bonding_start_time = 0.0

        # Cooldown / debounce timers
        self.last_sound_time = 0.0
        self.last_gesture_time = 0.0
        self.last_speech_time = 0.0
        self.last_bonding_time = 0.0
        self.last_smile_time = 0.0
        self.last_startle_time = 0.0
        self.last_search_sound_time = 0.0
        self.last_voice_clip_time = 0.0
        self.last_blink_time = time.time()
        self.last_organic_query_time = 0.0

        # Async Gemini organic cortex state
        self._organic_query_in_progress = False
        self._pending_organic_reaction: Optional[Dict[str, Any]] = None
        self._lock = threading.Lock()
        self.current_identified_person: Optional[str] = None

        # Exit velocity memory for searching sweep
        self.last_exit_vel_x = 0.0
        self.prev_state = BehaviorState.IDLE
        self.last_action: Optional[BehaviorAction] = None

    def _trigger_live_visual_stimulus(
        self,
        jpeg_bytes: bytes,
        stimulus_data: Dict[str, Any],
        debounce_sec: float = 12.0
    ) -> None:
        """
        Dispatches real-time camera image bytes to Gemini Vision to observe the user's
        facial expression, posture, and activity directly (NO pre-built phrases).
        Runs asynchronously in a background thread so 30 FPS head tracking never freezes.
        """
        now = time.time()
        if now - self.last_organic_query_time < debounce_sec:
            return

        with self._lock:
            if self._organic_query_in_progress:
                return
            self._organic_query_in_progress = True

        self.last_organic_query_time = now

        def _visual_cortex_worker():
            try:
                if self.brain and hasattr(self.brain, "react_to_live_visual"):
                    reaction = self.brain.react_to_live_visual(jpeg_bytes, stimulus_data)
                elif self.brain and hasattr(self.brain, "react_to_organic_stimulus"):
                    reaction = self.brain.react_to_organic_stimulus(stimulus_data)
                else:
                    event = stimulus_data.get("event", "companion_idle")
                    reaction = self._generate_offline_organism_reaction(event, stimulus_data)

                with self._lock:
                    self._pending_organic_reaction = reaction
            except Exception as e:
                print(f"[Alpha Visual Cortex] Error analyzing live visual: {e}")
            finally:
                with self._lock:
                    self._organic_query_in_progress = False

        thread = threading.Thread(target=_visual_cortex_worker, daemon=True)
        thread.start()

    def _trigger_organic_stimulus(self, stimulus_data: Dict[str, Any], debounce_sec: float = 12.0) -> None:
        """
        Dispatches real-time sensory perception to Gemini's neural cortex asynchronously.
        Does NOT block the 30 FPS vision / servo loop.
        """
        now = time.time()
        if now - self.last_organic_query_time < debounce_sec:
            return

        with self._lock:
            if self._organic_query_in_progress:
                return
            self._organic_query_in_progress = True

        self.last_organic_query_time = now

        def _cortex_worker():
            try:
                if self.brain and hasattr(self.brain, "react_to_organic_stimulus"):
                    reaction = self.brain.react_to_organic_stimulus(stimulus_data)
                else:
                    event = stimulus_data.get("event", "companion_idle")
                    reaction = self._generate_offline_organism_reaction(event, stimulus_data)

                with self._lock:
                    self._pending_organic_reaction = reaction
            except Exception as e:
                print(f"[Alpha Behavior Cortex] Error generating organic reaction: {e}")
            finally:
                with self._lock:
                    self._organic_query_in_progress = False

        thread = threading.Thread(target=_cortex_worker, daemon=True)
        thread.start()

    def _generate_offline_organism_reaction(self, event: str, data: Dict[str, Any]) -> Dict[str, Any]:
        """Generates dynamic organic reaction when operating without cloud brain."""
        if event == "sustained_contact":
            return {
                "speech": "Staring contest? You're definitely gonna lose, boss!",
                "emotion": Emotion.LOVE,
                "sound": "love",
                "gesture": "head_pet_reaction",
                "inner_thought": "Why is he looking at me like that? My gears are melting!"
            }
        elif event == "user_smile":
            return {
                "speech": "Hey, that smile is brighter than the Kerala sun, Akhil!",
                "emotion": Emotion.EXCITED,
                "sound": "excited",
                "gesture": "excited_wiggle",
                "inner_thought": "My favorite human is smiling at me! Best day ever."
            }
        elif event == "proximity_close":
            return {
                "speech": "Personal space, giant! My nose almost got squashed!",
                "emotion": Emotion.SURPRISED,
                "sound": "alert",
                "gesture": "alert_recoil",
                "inner_thought": "Too close! Does he want a high-five or a nose boop?"
            }
        elif event == "face_lost":
            return {
                "speech": "Hey! Where are the snacks going without me?",
                "emotion": Emotion.CONFUSED,
                "sound": "confused",
                "gesture": "confused_wobble",
                "inner_thought": "Hope he is not sneaking off to eat banana chips in secret!"
            }
        elif event == "face_sighted":
            return {
                "speech": "You're back! Did you bring me anything good?",
                "emotion": Emotion.HAPPY,
                "sound": "happy",
                "gesture": "curious_tilt",
                "inner_thought": "He's back at the desk. Time to hang out."
            }
        else:
            return {
                "speech": "Still going strong? You're glued to that screen, Akhil!",
                "emotion": Emotion.HAPPY,
                "sound": "happy",
                "gesture": "nod",
                "inner_thought": "Man, his focus is legendary. Time for a desk snack soon."
            }

    def process_vision(
        self,
        face: FaceTrackingResult,
        frame: Optional[Any] = None,
        allow_speech: bool = True
    ) -> BehaviorAction:
        """
        Takes real-time face tracking perception and computes the optimal
        emotional expression, physical pose, sound effect, and companion behavior.
        """
        now = time.time()
        sound_to_play: Optional[str] = None
        gesture_to_run: Optional[str] = None
        speech_msg: Optional[str] = None
        obs_log: Optional[str] = None
        inner_thought: Optional[str] = None
        observed_visual: Optional[str] = None
        trigger_blink = False
        trigger_wink = False

        # Extract JPEG frame if available for live multimodal observation
        jpeg_bytes: Optional[bytes] = None
        if frame is not None:
            try:
                import cv2
                _, buf = cv2.imencode(".jpg", frame, [int(cv2.IMWRITE_JPEG_QUALITY), 75])
                jpeg_bytes = buf.tobytes()
            except Exception:
                jpeg_bytes = None

        # Check if a live visual / organic reaction arrived from the Gemini neural cortex
        pending_reaction = None
        with self._lock:
            if self._pending_organic_reaction:
                pending_reaction = self._pending_organic_reaction
                self._pending_organic_reaction = None

        pending_emotion: Optional[Emotion] = None
        if pending_reaction and allow_speech:
            speech_msg = pending_reaction.get("speech")
            observed_visual = pending_reaction.get("observed_visual")
            identified_persons = pending_reaction.get("identified_persons", [])
            if identified_persons and isinstance(identified_persons, list):
                first_p = identified_persons[0]
                if isinstance(first_p, dict) and first_p.get("name"):
                    self.current_identified_person = first_p.get("name")
            if pending_reaction.get("emotion"):
                emo_candidate = pending_reaction["emotion"]
                if isinstance(emo_candidate, Emotion):
                    pending_emotion = emo_candidate
                else:
                    pending_emotion = Emotion.from_str(str(emo_candidate))
            if pending_reaction.get("sound"):
                sound_to_play = pending_reaction["sound"]
            if pending_reaction.get("gesture"):
                gesture_to_run = pending_reaction["gesture"]
            inner_thought = pending_reaction.get("inner_thought")
            if observed_visual:
                obs_log = f"[Live Vision] Observed: {observed_visual}"
            elif inner_thought:
                obs_log = f"[Organic Mind] {inner_thought}"
            self.last_speech_time = now

        # Natural autonomous eye blinking (every 3.8 to 5.5 seconds)
        if now - self.last_blink_time > 4.2:
            trigger_blink = True
            self.last_blink_time = now

        # =====================================================================
        # SCENARIO 1: Face is actively detected in camera feed
        # =====================================================================
        if face.found:
            self.last_seen_time = now
            self.last_exit_vel_x = face.velocity_x

            # Compute gaze and pan/tilt to center user in frame
            gaze_x = face.offset_x
            gaze_y = face.offset_y
            target_pan = face.offset_x * 45.0
            target_tilt = -face.offset_y * 25.0

            # Was user previously absent? -> DISCOVERY / GREETING!
            if self.current_state in (BehaviorState.IDLE, BehaviorState.SEARCHING, BehaviorState.DISAPPOINTED):
                self.current_state = BehaviorState.GREETING
                self.tracking_start_time = now
                emo = Emotion.CURIOUS

                if now - self.last_voice_clip_time > 90.0:
                    sound_to_play = "alpha_voice"
                    self.last_voice_clip_time = now
                    self.last_sound_time = now
                elif now - self.last_sound_time > 45.0:
                    sound_to_play = "curious"
                    self.last_sound_time = now

                if now - self.last_gesture_time > 15.0:
                    gesture_to_run = "curious_tilt"
                    self.last_gesture_time = now

                n_faces = getattr(face, "num_faces", 1)
                n_objs = len(getattr(face, "detected_objects", []))
                obj_tag = f" and {n_objs} objects" if n_objs > 0 else ""
                if n_faces > 1:
                    obs_log = f"Spotted {n_faces} people{obj_tag} in front of camera."
                elif self.current_identified_person:
                    obs_log = f"Spotted {self.current_identified_person}{obj_tag} in front of camera."
                else:
                    obs_log = f"Spotted person{obj_tag} in front of camera."

                # In visual companion mode, Alpha communicates via Wall-E eyes and chirps (speech only if explicitly requested)
                if allow_speech and (now - self.last_speech_time > 45.0):
                    stim = {
                        "event": "face_sighted",
                        "distance": face.distance_category,
                        "pan": target_pan,
                        "tilt": target_tilt
                    }
                    if not self.brain:
                        speech_msg = self._generate_offline_organism_reaction("face_sighted", stim)["speech"]
                        self.last_speech_time = now

            else:
                # User has been in view continuously -> Analyze human emotions & objects
                sustained_duration = now - self.tracking_start_time
                user_emo = getattr(face, "user_emotion", "neutral")

                # Emotion 1: Startled / Close Proximity
                if (user_emo == "surprised" or face.distance_category == "close") and (now - self.last_startle_time > 4.0):
                    just_startled = self.current_state != BehaviorState.STARTLED
                    self.current_state = BehaviorState.STARTLED
                    emo = Emotion.SURPRISED
                    self.last_startle_time = now

                    if just_startled:
                        sound_to_play = "alert"
                        self.last_sound_time = now
                        gesture_to_run = "alert_recoil"
                        self.last_gesture_time = now

                    if allow_speech and (now - self.last_speech_time > 10.0) and not self.brain:
                        speech_msg = self._generate_offline_organism_reaction("proximity_close", {})["speech"]
                        self.last_speech_time = now

                # Emotion 2: Smiling / Happy / Excited
                elif (user_emo in ("happy", "excited") or face.is_smiling) and (now - self.last_smile_time > 5.0):
                    just_smiled = self.current_state != BehaviorState.SMILING
                    self.current_state = BehaviorState.SMILING
                    emo = Emotion.EXCITED
                    self.last_smile_time = now

                    if just_smiled:
                        sound_to_play = "excited"
                        self.last_sound_time = now
                        gesture_to_run = "excited_wiggle"
                        self.last_gesture_time = now

                    obs_log = f"{self.current_identified_person or 'User'} smiled at Alpha."

                    if allow_speech and (now - self.last_speech_time > 12.0) and not self.brain:
                        speech_msg = self._generate_offline_organism_reaction("user_smile", {})["speech"]
                        self.last_speech_time = now

                # Emotion 3: Sustained Eye Contact (> 3.2s) -> Deep Loving Bond
                elif user_emo == "love" or (sustained_duration > 3.2 and (now - self.last_bonding_time > 12.0)) or (self.current_state == BehaviorState.BONDING and now - self.bonding_start_time < 3.5):
                    just_bonded = self.current_state != BehaviorState.BONDING
                    self.current_state = BehaviorState.BONDING
                    emo = Emotion.LOVE
                    if just_bonded:
                        self.last_bonding_time = now
                        self.bonding_start_time = now
                        trigger_wink = True

                    if just_bonded:
                        sound_to_play = "love"
                        self.last_sound_time = now
                        gesture_to_run = "head_pet_reaction"
                        self.last_gesture_time = now

                    obs_log = f"Maintained sustained affectionate eye contact with {self.current_identified_person or 'companion'}."

                    if just_bonded and allow_speech and (now - self.last_speech_time > 14.0) and not self.brain:
                        speech_msg = self._generate_offline_organism_reaction("sustained_contact", {})["speech"]
                        self.last_speech_time = now

                # Emotion 4: Curious Head Tilt
                elif user_emo == "curious":
                    just_curious = self.current_state != BehaviorState.GREETING
                    emo = Emotion.CURIOUS
                    if just_curious and (now - self.last_sound_time > 20.0):
                        sound_to_play = "curious"
                        self.last_sound_time = now
                        gesture_to_run = "curious_tilt"
                        self.last_gesture_time = now

                # Emotion 5: Focused / Working at desk (Quiet respectful watch mode)
                elif user_emo == "focused":
                    self.current_state = BehaviorState.TRACKING
                    emo = Emotion.ANALYZING  # Soft squint, focused companion watch
                    sound_to_play = None
                    gesture_to_run = None

                # Emotion 6: Sad / Melancholy
                elif user_emo == "sad":
                    emo = Emotion.SAD
                    if now - self.last_sound_time > 20.0:
                        sound_to_play = "sad"
                        self.last_sound_time = now
                        gesture_to_run = "curious_tilt"
                        self.last_gesture_time = now

                else:
                    # Normal active friendly tracking
                    self.current_state = BehaviorState.TRACKING
                    emo = Emotion.HAPPY

            if pending_emotion:
                emo = pending_emotion

            return BehaviorAction(
                state=self.current_state,
                emotion=emo,
                gaze_x=gaze_x,
                gaze_y=gaze_y,
                target_pan=target_pan,
                target_tilt=target_tilt,
                sound=sound_to_play,
                gesture=gesture_to_run,
                speech_message=speech_msg,
                observation_log=obs_log,
                inner_thought=inner_thought,
                observed_visual=observed_visual,
                trigger_blink=trigger_blink,
                trigger_wink=trigger_wink,
                num_faces=getattr(face, "num_faces", 1),
                identified_name=self.current_identified_person
            )

        # =====================================================================
        # SCENARIO 2: Face is absent / lost from camera feed
        # =====================================================================
        lost_duration = now - self.last_seen_time if self.last_seen_time > 0 else 999.0

        # Phase A: Just lost (0 - 3.0s) -> SEARCHING with confused head wobble!
        if lost_duration < 3.0:
            just_searching = self.current_state != BehaviorState.SEARCHING
            self.current_state = BehaviorState.SEARCHING
            emo = Emotion.CONFUSED

            if just_searching:
                sound_to_play = "confused"
                self.last_search_sound_time = now
                gesture_to_run = "confused_wobble"
                self.last_gesture_time = now

            # Sweep gaze in direction where user left
            sweep_dir = 0.6 if self.last_exit_vel_x >= 0 else -0.6
            gaze_x = sweep_dir
            gaze_y = 0.1
            target_pan = sweep_dir * 30.0
            target_tilt = 0.0

            if just_searching and allow_speech and (now - self.last_speech_time > 20.0):
                stim = {
                    "event": "face_lost",
                    "duration": lost_duration,
                    "pan": target_pan,
                    "tilt": target_tilt
                }
                if self.brain:
                    self._trigger_organic_stimulus(stim, debounce_sec=20.0)
                else:
                    speech_msg = self._generate_offline_organism_reaction("face_lost", stim)["speech"]
                    self.last_speech_time = now

            return BehaviorAction(
                state=self.current_state,
                emotion=emo,
                gaze_x=gaze_x,
                gaze_y=gaze_y,
                target_pan=target_pan,
                target_tilt=target_tilt,
                sound=sound_to_play,
                gesture=gesture_to_run,
                speech_message=speech_msg,
                observation_log="Searching for user who left frame.",
                inner_thought=inner_thought,
                trigger_blink=trigger_blink
            )

        # Phase B: Still absent (3.0 - 6.0s) -> DISAPPOINTED / Melancholy head droop
        elif lost_duration < 6.0:
            just_disappointed = self.current_state != BehaviorState.DISAPPOINTED
            self.current_state = BehaviorState.DISAPPOINTED
            emo = Emotion.SAD

            if just_disappointed or (now - self.last_gesture_time > 4.5):
                gesture_to_run = "sad_droop"
                self.last_gesture_time = now

            return BehaviorAction(
                state=self.current_state,
                emotion=emo,
                gaze_x=0.0,
                gaze_y=0.2,
                target_pan=0.0,
                target_tilt=-10.0,
                sound=None,
                gesture=gesture_to_run,
                speech_message=None,
                observation_log=None,
                inner_thought=None,
                trigger_blink=trigger_blink
            )

        # Phase C: Long absence (> 6.0s) -> IDLE rest state
        else:
            self.current_state = BehaviorState.IDLE
            emo = Emotion.IDLE

            return BehaviorAction(
                state=self.current_state,
                emotion=emo,
                gaze_x=0.0,
                gaze_y=0.0,
                target_pan=0.0,
                target_tilt=0.0,
                sound=None,
                gesture=None,
                speech_message=None,
                observation_log=None,
                inner_thought=None,
                trigger_blink=trigger_blink
            )

    def apply_action(self, robot: Any, action: BehaviorAction) -> None:
        """Dispatches computed behavior actions to robot hardware, eyes, and voice."""
        self.last_action = action

        # Companion Event Notification
        if action.state != self.prev_state:
            state_tags = {
                BehaviorState.GREETING: "[GREETING]",
                BehaviorState.TRACKING: "[TRACKING]",
                BehaviorState.BONDING: "[BONDING]",
                BehaviorState.SMILING: "[SMILE MIRROR]",
                BehaviorState.STARTLED: "[PROXIMITY STARTLE]",
                BehaviorState.SEARCHING: "[SEARCHING]",
                BehaviorState.DISAPPOINTED: "[DISAPPOINTED]",
                BehaviorState.IDLE: "[IDLE REST]",
            }
            tag = state_tags.get(action.state, f"[{action.state.value.upper()}]")
            try:
                print(f"[Alpha Behavior] {tag} | Emotion: {action.emotion.value.upper()} | Pan: {action.target_pan:+.1f} deg | Tilt: {action.target_tilt:+.1f} deg")
            except Exception:
                pass
            self.prev_state = action.state

        # 1. Update Dual Eye Expression & Gaze
        robot.eyes.set_emotion(action.emotion)
        robot.eyes.set_gaze(action.gaze_x, action.gaze_y)

        if action.trigger_wink:
            robot.eyes.wink()
        elif action.trigger_blink:
            robot.eyes.blink()

        # 2. Update Neck Servos
        robot.motion.set_head_pose(action.target_pan, action.target_tilt)

        # 3. Physical Gesture
        if action.gesture:
            if hasattr(robot.motion, action.gesture):
                getattr(robot.motion, action.gesture)()

        # 4. Sound Synthesis
        if action.sound and hasattr(robot.voice, "play_sound"):
            robot.voice.play_sound(action.sound)

        # 5. Spoken Speech (Organic Living Vocalization)
        if action.speech_message and hasattr(robot.voice, "speak") and robot.voice.voice_enabled:
            robot.voice.speak(action.speech_message, emotion=action.emotion, with_chirp=True)

        # 6. Memory Log & Organism Inner Thought Log
        if action.inner_thought and hasattr(robot, "db") and hasattr(robot.db, "log_observation"):
            robot.db.log_observation(f"[Organic Instinct] {action.inner_thought}")
        elif action.observation_log and hasattr(robot, "db") and hasattr(robot.db, "log_observation"):
            robot.db.log_observation(action.observation_log)


